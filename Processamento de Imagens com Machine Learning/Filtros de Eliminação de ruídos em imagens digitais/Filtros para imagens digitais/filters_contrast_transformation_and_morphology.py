"""### Aliasing, rotating and rescaling
You'll make this cat image upright by rotating it 90 degrees and then rescaling it two times (with and without anti-aliasing).
"""
print("--- 6. Rotação e Redimensionamento (Anti-Aliasing) ---")
image_cat = plt.imread(get_image_path('image_cat.jpg'))

# Rotate the image 90 degress clockwise
rotated_cat_image = rotate(image_cat, -90)

# Rescale (handling deprecation of multichannel in newer skimage versions)
try:
    rescaled_with_aa = rescale(rotated_cat_image, 1/4, anti_aliasing=True, multichannel=True)
    rescaled_without_aa = rescale(rotated_cat_image, 1/4, anti_aliasing=False, multichannel=True)
except TypeError:
    rescaled_with_aa = rescale(rotated_cat_image, 1/4, anti_aliasing=True, channel_axis=-1)
    rescaled_without_aa = rescale(rotated_cat_image, 1/4, anti_aliasing=False, channel_axis=-1)

# Plot and save comparison
plt.figure(figsize=(10, 5))
plt.subplot(1, 2, 1)
show_image(rescaled_with_aa, 'Transformed with anti aliasing')
plt.subplot(1, 2, 2)
show_image(rescaled_without_aa, 'Transformed without anti aliasing')
plt.tight_layout()
plt.savefig(os.path.join(resultados_dir, '6_cat_rescaled_comparison.png'))
plt.close()
print("Resultado salvo em 'resultados/6_cat_rescaled_comparison.png'\n")


