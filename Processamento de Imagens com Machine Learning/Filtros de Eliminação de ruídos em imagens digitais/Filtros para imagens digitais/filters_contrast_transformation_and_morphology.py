# Morphology
# =====================================================================

"""### Handwritten letters
Apply the morphological operation (erosion) that will discard the pixels near the letter boundaries.
"""
print("--- 9. Morfologia: Erosão (Letra R) ---")
upper_r_image_raw = plt.imread(get_image_path('r5.png'))

# Ensure correct conversion to gray and then binary
if upper_r_image_raw.ndim == 3:
    if upper_r_image_raw.shape[2] == 4:
        upper_r_image_raw = color.rgba2rgb(upper_r_image_raw)
    upper_r_image_gray = color.rgb2gray(upper_r_image_raw)
else:
    upper_r_image_gray = upper_r_image_raw

upper_r_image_bin = upper_r_image_gray > 0.5

# Obtain the eroded shape
eroded_image_shape = morphology.erosion(upper_r_image_bin)

# Plot and save comparison
plt.figure(figsize=(10, 5))
plt.subplot(1, 2, 1)
show_image(upper_r_image_bin, 'Original (Binary)')
plt.subplot(1, 2, 2)
show_image(eroded_image_shape, 'Eroded image')
plt.tight_layout()
plt.savefig(os.path.join(resultados_dir, '9_r5_eroded.png'))
plt.close()
print("Resultado salvo em 'resultados/9_r5_eroded.png'\n")


"""### Improving thresholded image
In this exercise, we'll try to reduce the noise of a thresholded image using the dilation morphological operation.
"""
print("--- 10. Morfologia: Dilatação (Mapa Mundi) ---")
world_image_raw = plt.imread(get_image_path('world_image_binary.jpg'))

# Ensure correct conversion to gray and then binary
if world_image_raw.ndim == 3:
    if world_image_raw.shape[2] == 4:
        world_image_raw = color.rgba2rgb(world_image_raw)
    world_image_gray = color.rgb2gray(world_image_raw)
else:
    world_image_gray = world_image_raw

world_image_bin = world_image_gray > 0.5

# Obtain the dilated image
dilated_image = morphology.dilation(world_image_bin)

# Plot and save comparison
plt.figure(figsize=(10, 5))
plt.subplot(1, 2, 1)
show_image(world_image_bin, 'Original (Binary)')
plt.subplot(1, 2, 2)
show_image(dilated_image, 'Dilated image')
plt.tight_layout()
plt.savefig(os.path.join(resultados_dir, '10_world_dilated.png'))
plt.close()
print("Resultado salvo em 'resultados/10_world_dilated.png'\n")

