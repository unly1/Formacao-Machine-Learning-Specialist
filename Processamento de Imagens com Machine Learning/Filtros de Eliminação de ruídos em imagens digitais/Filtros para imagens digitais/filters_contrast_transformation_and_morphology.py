import os
import urllib.request
import numpy as np
import matplotlib.pyplot as plt
from skimage import color, exposure, data, morphology
from skimage.filters import sobel, gaussian
from skimage.transform import rotate, rescale, resize

# --- Setup local paths and download directories ---
script_dir = os.path.dirname(os.path.abspath(__file__))
downloads_dir = os.path.join(script_dir, "downloads")
resultados_dir = os.path.join(script_dir, "resultados")

os.makedirs(downloads_dir, exist_ok=True)
os.makedirs(resultados_dir, exist_ok=True)

print(f"Diretório de downloads: {downloads_dir}")
print(f"Diretório de resultados: {resultados_dir}\n")

def get_image_path(filename):
    """
    Checks if the image exists in the local downloads folder.
    If not, downloads it from the source GitHub repository.
    """
    local_path = os.path.join(downloads_dir, filename)
    if not os.path.exists(local_path):
        print(f"Baixando imagem '{filename}'...")
        url = f"https://github.com/goodboychan/chans_jupyter/raw/main/_notebooks/dataset/{filename}"
        try:
            urllib.request.urlretrieve(url, local_path)
            print(f"'{filename}' baixada com sucesso.")
        except Exception as e:
            print(f"Erro ao baixar de '{url}': {e}. Tentando fallback...")
            fallback_url = f"https://raw.githubusercontent.com/goodboychan/chans_jupyter/master/_notebooks/dataset/{filename}"
            try:
                urllib.request.urlretrieve(fallback_url, local_path)
                print(f"'{filename}' baixada com sucesso (fallback).")
            except Exception as e2:
                print(f"Erro ao baixar de '{fallback_url}': {e2}")
                raise e2
    return local_path

def show_image(image, title='Image', cmap_type='gray'):
    plt.imshow(image, cmap=cmap_type)
    plt.title(title)
    plt.axis('off')

# =====================================================================
# Jump into filtering
# =====================================================================

"""### Edge detection
In this exercise, you'll detect edges in an image by applying the Sobel filter.
"""
print("--- 1. Detecção de Bordas (Sobel) ---")
soaps_image = plt.imread(get_image_path('soap_image.jpg'))

# Make the image grayscale
soaps_image_gray = color.rgb2gray(soaps_image)

# apply edge detection filters
edge_sobel = sobel(soaps_image_gray)

# Plot and save comparison
plt.figure(figsize=(10, 5))
plt.subplot(1, 2, 1)
show_image(soaps_image, 'Original')
plt.subplot(1, 2, 2)
show_image(edge_sobel, 'Edges with Sobel')
plt.tight_layout()
plt.savefig(os.path.join(resultados_dir, '1_edge_detection_sobel.png'))
plt.close()
print("Resultado salvo em 'resultados/1_edge_detection_sobel.png'\n")


"""### Blurring to reduce noise
In this exercise you will reduce the sharpness of an image of a building taken during a London trip, through filtering.
"""
print("--- 2. Suavização Gaussiana (Blur) ---")
building_image = plt.imread(get_image_path('building_image.jpg'))

# Apply filter (handling deprecation of multichannel in newer skimage versions)
try:
    gaussian_image = gaussian(building_image, multichannel=True)
except TypeError:
    gaussian_image = gaussian(building_image, channel_axis=-1)

# Plot and save comparison
plt.figure(figsize=(10, 5))
plt.subplot(1, 2, 1)
show_image(building_image, 'Original')
plt.subplot(1, 2, 2)
show_image(gaussian_image, 'Reduced sharpness Gaussian')
plt.tight_layout()
plt.savefig(os.path.join(resultados_dir, '2_gaussian_blurring.png'))
plt.close()
print("Resultado salvo em 'resultados/2_gaussian_blurring.png'\n")


